export function icon(name, cls) {
  const path = ICON_PATHS[name];
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'currentColor');
  svg.setAttribute('aria-hidden', 'true');
  if (cls) svg.setAttribute('class', cls);
  const p = document.createElementNS('http://www.w3.org/2000/svg', 'path');
  p.setAttribute('d', path || '');
  svg.appendChild(p);
  return svg;
}

/** Adds a long-press handler (mirrors Compose's combinedClickable onLongClick). */
export function onLongPress(el, handler, ms = 500) {
  let timer = null;
  let fired = false;

  const start = () => {
    fired = false;
    timer = setTimeout(() => { fired = true; handler(); }, ms);
  };
  const cancel = () => { if (timer) { clearTimeout(timer); timer = null; } };

  el.addEventListener('pointerdown', start);
  el.addEventListener('pointerup', cancel);
  el.addEventListener('pointerleave', cancel);
  el.addEventListener('pointercancel', cancel);
  el.addEventListener('contextmenu', (e) => { e.preventDefault(); });
  el.addEventListener('click', (e) => {
    if (fired) { e.preventDefault(); e.stopImmediatePropagation(); fired = false; }
  }, true);
  return el;
}
