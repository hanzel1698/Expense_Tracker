/**
 * h('div.card', { onclick, style }, ...children)
 * The tag accepts `tag.class1.class2#id` shorthand. Children may be nodes,
 * strings, numbers, arrays, or null/false/undefined (skipped).
 */
export function h(spec, props, ...children) {
  const [tagAndId, ...classes] = String(spec).split('.');
  const [tag, id] = tagAndId.split('#');
  const el = document.createElement(tag || 'div');
  if (id) el.id = id;
  if (classes.length) el.classList.add(...classes);

  if (props) {
    for (const [key, value] of Object.entries(props)) {
      if (value === null || value === undefined || value === false) continue;
      if (key === 'class' || key === 'className') {
        el.classList.add(...String(value).split(/\s+/).filter(Boolean));
      } else if (key === 'style' && typeof value === 'object') {
        Object.assign(el.style, value);
      } else if (key === 'dataset') {
        Object.assign(el.dataset, value);
      } else if (key.startsWith('on') && typeof value === 'function') {
        el.addEventListener(key.slice(2), value);
      } else if (key === 'html') {
        el.innerHTML = value;
      } else if (key in el && key !== 'list' && key !== 'type' && key !== 'role') {
        el[key] = value;
      } else {
        el.setAttribute(key, value === true ? '' : value);
      }
    }
  }

  append(el, children);
  return el;
}

export function append(el, children) {
  for (const child of children.flat(Infinity)) {
    if (child === null || child === undefined || child === false || child === true) continue;
    el.appendChild(child instanceof Node ? child : document.createTextNode(String(child)));
  }
  return el;
}

export function clear(el) {
  while (el.firstChild) el.removeChild(el.firstChild);
  return el;
}

/** Text node convenience: text('span.title-medium', 'Hello') */
export function text(spec, value, props) {
  return h(spec, props, value);
}

